export interface HelpArticle {
  id: string;
  slug: string;
  title: string;
  category: string;
  keywords: string[];
  /** Extra search phrases (Urdu/Roman, common typos) */
  searchAliases?: string[];
  /** One-line summary for search results */
  shortDescription?: string;
  /** When do I use this? */
  whenToUse?: string;
  /** Optional staff tip box on guide detail */
  tip?: string;
  /** User-facing menu path for Where to go */
  navigationPath?: string[];
  whoCan: string;
  permissions: string;
  /** Role filter keys: owner, doctor, nurse, receptionist, laboratory, pharmacy, accountant, ward */
  roles?: string[];
  /** Module gating for module guides */
  module?: 'clinical' | 'pharmacy' | 'laboratory' | 'ward' | 'accounts' | 'setup' | 'nursery';
  beforeStart: string[];
  steps: string[];
  after: string[];
  financial?: string[];
  errors?: string[];
  related: string[];
  route?: string;
  /** When true, Help Center shows “Start interactive tutorial” → opens route with ?tutorial=1 */
  hasInteractiveTutorial?: boolean;
}

